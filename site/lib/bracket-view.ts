export type BracketRow = {
  round: number; position: number; seed: number | null; team_a_id: string | null;
  team_b_id: string | null; source_slot_a: string | null; source_slot_b: string | null; is_bye: number;
};

export type BracketTeam = { id: string; name: string; abbreviation: string | null; category: "bid" | "playin" | "outside" };
export type BracketSide = { label: string; seed: number | null; pairId: string | null };
export type BracketMatch = { id: string; label: string; sides: [BracketSide, BracketSide | null]; bye: boolean };
export type BracketRound = { number: number; label: string; matches: BracketMatch[] };
export type BracketView = {
  slots: { seed: number; label: string; pairId: string | null }[];
  playins: { id: string; seed: number; first: string; second: string }[];
  playinByes: { seed: number; name: string }[];
  rounds: BracketRound[];
  champion: string | null;
};

type Source = { kind: "slot"; slotId: string } | { kind: "winner"; matchId: string };

function source(value: string | null): Source | null {
  if (!value) return null;
  const parsed: unknown = JSON.parse(value);
  if (!parsed || typeof parsed !== "object" || !("kind" in parsed) || !("slotId" in parsed || "matchId" in parsed))
    throw new Error("Invalid published bracket source");
  if (parsed.kind === "slot" && "slotId" in parsed && typeof parsed.slotId === "string") return { kind: "slot", slotId: parsed.slotId };
  if (parsed.kind === "winner" && "matchId" in parsed && typeof parsed.matchId === "string") return { kind: "winner", matchId: parsed.matchId };
  throw new Error("Invalid published bracket source");
}

/** IDs are generated by the bracket engine; only round-zero slots hold teams. */
export function bracketView(rows: BracketRow[], teams: BracketTeam[]): BracketView {
  const names = new Map(teams.map(team => [team.id, team.name]));
  const categories = new Map(teams.map(team => [team.id, team.category]));
  const name = (id: string | null) => id === null ? "Unknown team" : names.get(id) ?? id;
  const slots = rows.filter(row => row.round === 0).sort((a, b) => a.position - b.position).map(row => {
    if (row.seed === null || row.team_a_id === null) throw new Error("Invalid published main slot");
    const pairId = row.team_b_id === null ? null : row.source_slot_a;
    return { seed: row.seed, label: row.team_b_id === null ? name(row.team_a_id) : `${name(row.team_a_id)} / ${name(row.team_b_id)}`,
      first: name(row.team_a_id), second: row.team_b_id === null ? null : name(row.team_b_id), pairId,
      playinBye: row.team_b_id === null && categories.get(row.team_a_id) === "playin" };
  });
  const bySeed = new Map(slots.map(slot => [slot.seed, slot]));
  const seen = new Set<string>();
  const resolve = (entry: Source): BracketSide => {
    if (entry.kind === "winner") {
      if (!seen.has(entry.matchId)) throw new Error("Unknown published match source");
      return { label: `Winner of ${entry.matchId.replace(/^main-(\d+)-(\d+)$/, "round $1, matchup $2")}`, seed: null, pairId: null };
    }
    const match = /^main-slot-(\d+)(?:-\d+)?$/.exec(entry.slotId);
    const slot = match ? bySeed.get(Number(match[1])) : undefined;
    if (!slot) throw new Error("Unknown published seed source");
    return { label: slot.label, seed: slot.seed, pairId: slot.pairId };
  };
  const rounds = [...new Set(rows.filter(row => row.round > 0).map(row => row.round))].sort((a, b) => a - b)
    .map(number => ({ number, label: `Main bracket round ${number}`, matches: rows.filter(row => row.round === number)
      .sort((a, b) => a.position - b.position).map(row => {
        const first = source(row.source_slot_a);
        const second = source(row.source_slot_b);
        if (!first || (!second && !row.is_bye)) throw new Error("Invalid published matchup");
        const sides: [BracketSide, BracketSide | null] = [resolve(first), second ? resolve(second) : null];
        const id = `main-${number}-${row.position + 1}`;
        seen.add(id);
        return { id, label: `Round ${number}, matchup ${row.position + 1}`, sides, bye: Boolean(row.is_bye) };
      }) }));
  const finalMatch = rounds.at(-1)?.matches[0];
  return { slots: slots.map(({ seed, label, pairId }) => ({ seed, label, pairId })),
    playins: slots.filter(slot => slot.second !== null).map(slot => ({ id: slot.pairId ?? `seed-${slot.seed}`, seed: slot.seed, first: slot.first, second: slot.second! })),
    playinByes: slots.filter(slot => slot.playinBye).map(slot => ({ seed: slot.seed, name: slot.first })),
    rounds, champion: finalMatch ? `Winner of ${finalMatch.label.toLowerCase()}` : null };
}
